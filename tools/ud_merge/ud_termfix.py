    (None, r'法力恢復', '魔力恢復'),
    (None, r'法力消耗', '魔力消耗'),
    (None, r'法力', '魔力'),
    (None, r'射程', '攻擊距離'),
    (None, r'存活時間', '持續時間'),
    (r'перезарядк', r'冷卻(?!時間)(?=\s*[：:]|\s*\{|\s*\d)', '冷卻時間'),
    (r'время действия|длительност|время жизни', r'持續(?!時間)(?=\s*[：:]|\s*\{\d+\}\s*秒)', '持續時間'),
    # 「+N% X 抗性」是百分比減傷（защита от X）→ X防禦；不帶數字的「抵抗 X」是免疫旗標（сопротивление）→ X抗性
    # （+N% X抗性 → X防禦 改在 fix() 裡依「защита от X」逐一判斷）
    (r'сопротивлени', r'抵抗(點燃|易燃|流血|疾病|冰凍|詛咒|震擊|咒印|虛弱|易傷)(?:與|和|、)(點燃|易燃|流血|疾病|冰凍|詛咒|震擊|咒印|虛弱|易傷)', r'\1與\2抗性'),
    (r'сопротивлени', r'抵抗(點燃|易燃|流血|疾病|冰凍|詛咒|震擊|咒印|虛弱|易傷)', r'\1抗性'),

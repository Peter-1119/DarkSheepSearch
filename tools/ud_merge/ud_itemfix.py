FIELDS = ('ides', 'utub')
hits = collections.Counter()


def apply(k, m, s):
    """k＝物件 ID，m＝欄位，s＝已翻好的字串（或 None）。"""
    if k not in FIX or m not in FIELDS or s is None:
        return s
    for a, b in FIX[k]:
        if a in s:
            s = s.replace(a, b)
            hits[(k, a)] += 1
    return s


